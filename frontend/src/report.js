export function buildReportHTML({ kind, filename, analysis, llm, generatedAt }) {
  const a = analysis || {}
  const label = KIND_LABEL[kind] || 'Analysis'
  const when = generatedAt || new Date()
  const verdict = a.verdict || 'healthy'
  const body =
    kind === 'heap' ? heapBody(a) :
    kind === 'thread' ? threadBody(a) :
    kind === 'gc' ? gcBody(a) : ''

  const title = `POSTMORTEM — ${label}${filename ? ` — ${filename}` : ''}`

  return `<!doctype html>
<html lang="en"><head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(title)}</title>
<style>${CSS}</style>
</head><body><main>
<header>
  <h1>POSTMORTEM — ${esc(label)}</h1>
  <div class="meta">
    ${filename ? `<code>${esc(filename)}</code> · ` : ''}generated ${esc(when.toISOString().replace('T', ' ').replace(/\..+/, ' UTC'))}
  </div>
</header>

<div class="verdict ${esc(verdict)}">
  <div class="v">${esc(verdict)}</div>
  <p>${esc(a.summary || '')}</p>
</div>

${coverageSection(a)}
${llmSection(llm)}
${findingsSection(a.findings)}
${body}

<footer>
  Produced by POSTMORTEM. Ranked tables show the top ${TOP_N} entries; the full
  data stays in the workbench session. Shallow sizes use the
  ${esc(a.sizing_model || 'assumed')} object layout — hprof does not record object
  headers, so that part is inferred, not measured.
</footer>
</main></body></html>`
}

/** Build the report and hand it to the browser as a download. */
export function downloadReport({ kind, filename, analysis, llm }) {
  const html = buildReportHTML({ kind, filename, analysis, llm })
  const blob = new Blob([html], { type: 'text/html;charset=utf-8' })
  const url = URL.createObjectURL(blob)
  const stem = (filename || kind || 'analysis').replace(/[^\w.-]+/g, '_')
  const stamp = new Date().toISOString().slice(0, 19).replace(/[:T]/g, '')
  const link = document.createElement('a')
  link.href = url
  link.download = `postmortem-${kind}-${stem}-${stamp}.html`
  document.body.appendChild(link)
  link.click()
  link.remove()
  setTimeout(() => URL.revokeObjectURL(url), 0)
}
